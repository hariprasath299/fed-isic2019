def src(path):
    if os.path.exists(path) and path not in [p for p, _ in SOURCES]:
        SOURCES.append((path, datetime.fromtimestamp(os.path.getmtime(path))))
    return path


def rows(path):
    with open(src(path)) as f:
        return list(csv.DictReader(f))


def last_row(path, **flt):
    for x in reversed(rows(path)):
        if all(x[k] == v for k, v in flt.items()):
            return x
    return None


def cache(run):
    hits = sorted(glob.glob(os.path.join(RES, "_cache", f"{run}_*.npz")))
    if not hits:
        return None
    z = np.load(src(hits[-1]))
    return {c: (z[f"y{c}"], z[f"p{c}"]) for c in range(NC)}


def fmt(v, n=4):
    return "--" if v is None else f"{v:.{n}f}"


