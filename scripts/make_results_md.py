def section_7_paired(facts, n_boot, alpha, boot_seed):
    emit("## 7. Paired deltas — pooled minus local")
    emit()
    emit("Estimator: difference of seed-means under a shared stratified resample "
         "(2026-08-20 amendment). Significant iff the CI excludes 0. The quantum "
         "column is that row's metric resolution — a delta below its own quantum "
         "cannot be represented by the metric.")
    emit()
    pcp = [cache(f"pooled_finetune_s{s}") for s in SEEDS]
    pcl = [cache(f"local_finetune_s{s}") for s in SEEDS]
    pcp = [x for x in pcp if x is not None]
    pcl = [x for x in pcl if x is not None]
    if not pcp or not pcl:
        emit("Cached predictions unavailable; deltas not computed.")
        emit()
        return None
    res = seed_mean_paired_delta(pcp, pcl, n_boot, alpha, boot_seed)
    qs = {f"c{c}": facts[c]["quantum"] for c in range(NC)}
    for name, cs in STRATA.items():
        qs[name] = max(facts[c]["quantum"] for c in cs)
    qs["union"] = facts[0]["quantum"]
    qs["mean_centres"] = float(np.mean([facts[c]["quantum"] for c in range(NC)]))
    labels = {**{f"c{c}": f"centre {c}" for c in range(NC)},
              **{n: f"stratum {n}" for n in STRATA},
              "union": "**pooled union**", "mean_centres": "**mean over centres**"}
    order = [f"c{c}" for c in range(NC)] + list(STRATA) + ["union", "mean_centres"]
    emit("| row | delta | 95% CI | significant | seeds (pooled/local) | row quantum (pts) |")
    emit("|---|---|---|---|---|---|")
    for k in order:
        if k not in res:
            continue
        d, lo, hi = res[k]
        sig = "**yes**" if (lo > 0 or hi < 0) else "no"
        q = qs.get(k)
        note = f"{q:.2f}" + (" **coarse**" if q and q > 1.0 else "")
        emit(f"| {labels[k]} | {d:+.4f} | [{lo:+.4f}, {hi:+.4f}] | {sig} | "
             f"{len(pcp)}/{len(pcl)} | {note} |")
    emit()
    emit(f"Bootstrap: {n_boot} resamples, {100*(1-alpha):.0f}% percentile, "
         f"rng seed {boot_seed}.")
    emit()
    return res


def curve_stats(e, v, lo, hi):
    m = (e >= lo) & (e <= hi)
    x = e[m].astype(float)
    y = v[m] * 100.0
    n = len(x)
    X = np.vstack([np.ones(n), x]).T
    beta, *_ = np.linalg.lstsq(X, y, rcond=None)
    resid = y - X @ beta
    dof = n - 2
    s2 = (resid ** 2).sum() / dof
    se = float(np.sqrt(s2 * np.linalg.inv(X.T @ X)[1, 1]))
    t = beta[1] / se
    from scipy import stats as st  # noqa
    crit = st.t.ppf(0.975, dof)
    verdict = "neg" if (t < -crit) else ("pos" if t > crit else "null")
    return float(beta[1]), se, float(t), float(np.abs(np.diff(y)).mean()), verdict


def section_8_curves():
    emit("## 8. Curve diagnostics")
    emit()
    emit("OLS slope over the **final half** of training (epochs 21-40), in points "
         "per epoch. Verdict is a two-sided t-test at alpha 0.05: `neg` = "
         "significant decline, `pos` = significant improvement, `null` = not "
         "distinguishable from flat. This is the protocol trigger under the "
         "2026-08-20 resolution-scaling amendment.")
    emit()
    emit("| run | slope (pts/ep) | SE | t | verdict | mean abs step (pts) |")
    emit("|---|---|---|---|---|---|")
    tally = {"neg": 0, "pos": 0, "null": 0}
    for s in SEEDS:
        p = os.path.join(RES, f"pooled_finetune_s{s}.csv")
        if not os.path.exists(p):
            continue
        r = rows(p)
        e = np.array([int(x["round"]) for x in r])
        v = np.array([float(x["bal_acc_pooled"]) for x in r])
        sl, se, t, step, verd = curve_stats(e, v, 21, 40)
        tally[verd] += 1
        emit(f"| pooled s{s} | {sl:+.3f} | {se:.3f} | {t:+.2f} | {verd} | {step:.2f} |")
    for s in SEEDS:
        p = os.path.join(RES, f"local_finetune_s{s}.csv")
        if not os.path.exists(p):
            continue
        r = rows(p)
        for c in range(NC):
            rr = [x for x in r if x["client"] == str(c)]
            e = np.array([int(x["round"]) for x in rr])
            v = np.array([float(x["bal_acc_own"]) for x in rr])
            sl, se, t, step, verd = curve_stats(e, v, 21, 40)
            tally[verd] += 1
            emit(f"| local s{s} c{c} | {sl:+.3f} | {se:.3f} | {t:+.2f} | {verd} | {step:.2f} |")
    emit()
    tot = sum(tally.values())
    emit(f"Of {tot} curves: **{tally['neg']} declining**, {tally['pos']} improving, "
         f"{tally['null']} flat.")
    emit()


