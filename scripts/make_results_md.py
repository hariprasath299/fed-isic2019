def dataset_facts():
    d = np.load(src("data/features/test.npz"))
    dtr = np.load(src("data/features/train.npz"))
    Y, C = d["labels"], d["centers"]
    Ytr, Ctr = dtr["labels"], dtr["centers"]
    out = {}
    for c in range(NC):
        y = Y[C == c]
        cnt = np.bincount(y, minlength=8)
        pres = cnt[cnt > 0]
        out[c] = {
            "train_n": int((Ctr == c).sum()),
            "test_n": len(y),
            "counts": cnt.tolist(),
            "n_present": len(pres),
            "min_count": int(pres.min()),
            "quantum": 100.0 / (len(pres) * int(pres.min())),
        }
    return out


